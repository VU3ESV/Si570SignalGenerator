# PlatformIO pre-build script: writes the build time to include/build_stamp.h.
#
# __DATE__/__TIME__ in main.cpp only change when main.cpp itself is recompiled, and
# PlatformIO skips that when its contents are unchanged, so the stamp went stale whenever
# only other files changed. Rewriting this header on every build forces main.cpp to be
# recompiled, and nothing else.
import os
import time

Import("env")  # noqa: F821 (provided by PlatformIO)

path = os.path.join(env.subst("$PROJECT_INCLUDE_DIR"), "build_stamp.h")  # noqa: F821
stamp = time.strftime("%b %d %Y %H:%M:%S")
with open(path, "w") as f:
    f.write("// Generated by tools/build_stamp.py on every build. Do not edit.\n")
    f.write("#pragma once\n")
    f.write('#define SIGGEN_BUILD_STAMP "%s"\n' % stamp)
